/// 核心状态机的阶段定义。
library;

/// 屏幕时间管理流程所处的阶段。
///
/// 状态流转：
/// ```
/// tracking ──累计亮屏达到阈值──▶ quiz
///     ▲                          │
///     │                  答对达标 │ 答错/放弃/无题库
///     │                          ▼
///     └────────休息结束──────── resting
/// ```
enum AppPhase {
  /// 正常计时：屏幕点亮期间累计亮屏时长。
  tracking,

  /// 豁免答题：必须完成本轮答题，答对达标才能回到 [tracking]，
  /// 答错或放弃则进入 [resting]。
  quiz,

  /// 全屏强制休息：休息期间不计亮屏时长，结束后回到 [tracking]
  /// 并重新开始累计下一轮阈值。
  resting,
}
